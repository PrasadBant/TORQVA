    QUALITY_RESTORED = "QUALITY_RESTORED"
    NOT_CONFIRMED = "NOT_CONFIRMED"
    PERSISTS = "PERSISTS"
    HYPOTHESES_RANKED = "HYPOTHESES_RANKED"
    GATE_ACT = "GATE_ACT"
