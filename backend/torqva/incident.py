    GATE_STOP = "GATE_STOP"
    GATE_ESCALATE = "GATE_ESCALATE"
    MORE_DATA_READY = "MORE_DATA_READY"
    TEST_APPROVED = "TEST_APPROVED"
    TEST_REJECTED = "TEST_REJECTED"
    TEST_COMPLETED = "TEST_COMPLETED"
    TEST_ABORTED = "TEST_ABORTED"
