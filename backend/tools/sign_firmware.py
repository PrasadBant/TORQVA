"""Release signing for the TORQVA Firmware Manager (offline; run it yourself, deliberately). Nothing here flashes, uploads or opens a port.

    python tools/sign_firmware.py keygen --out-dir <private folder OUTSIDE the repository>
        writes release_signing_key.pem (PRIVATE, encrypted with a passphrase you type) and release_public_key.pem
    python tools/sign_firmware.py export-header --pub <release_public_key.pem> [--out ../esp32/torqva_fw/src/ota_pubkey.h]
        writes the PUBLIC key into the firmware header the device verifies with (git-ignored; rebuild the firmware afterwards)
    python tools/sign_firmware.py sign --key <release_signing_key.pem> --bin <.pio/build/esp32s3/firmware.bin>
        prints the base64 signature to paste into the Firmware Manager upload (and writes <bin>.sig next to the image)

The signature is ECDSA P-256 / SHA-256 over "torqva-fw|1|<version>|<size>|<sha256 hex>|esp32s3". The version is read from the TORQVA_FW_ID string compiled
into the image, exactly as the backend and the device do. The backend verifies with TORQVA_OTA_PUBLIC_KEY (the same public key file).
The private key never belongs in the repository, the frontend or the backend host's configuration: only this tool reads it.
"""
import argparse
import base64
import getpass
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from torqva.firmware import FirmwareError, canonical, firmware_identity, parse_esp_image  # noqa: E402

REPO = Path(__file__).resolve().parents[2]


def _inside_repo(p: Path) -> bool:
    try:
        p.resolve().relative_to(REPO)
        return True
    except ValueError:
        return False


def keygen(a) -> int:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    out = Path(a.out_dir)
    if _inside_repo(out):
        print("refusing: --out-dir is inside the repository; keep the private key outside it", file=sys.stderr)
        return 2
    out.mkdir(parents=True, exist_ok=True)
    if any(out.iterdir()):
        print("refusing: --out-dir is not empty", file=sys.stderr)
        return 2
    pw = a.passphrase if a.passphrase is not None else getpass.getpass("passphrase for the private key (empty = unencrypted, development only): ")
    key = ec.generate_private_key(ec.SECP256R1())
    enc = serialization.BestAvailableEncryption(pw.encode()) if pw else serialization.NoEncryption()
    (out / "release_signing_key.pem").write_bytes(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, enc))
    (out / "release_public_key.pem").write_bytes(key.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo))
    print(f"written: {out / 'release_signing_key.pem'} (PRIVATE{'' if pw else ', UNENCRYPTED: development only'})")
    print(f"written: {out / 'release_public_key.pem'} (public: TORQVA_OTA_PUBLIC_KEY for the backend; export-header for the firmware)")
    return 0


def export_header(a) -> int:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    pem = Path(a.pub).read_bytes()
    key = serialization.load_pem_public_key(pem)
    if not isinstance(key, ec.EllipticCurvePublicKey) or key.curve.name != "secp256r1":
        print("refusing: not an ECDSA P-256 public key", file=sys.stderr)
        return 2
    if b"PRIVATE" in pem:
        print("refusing: that is a private key", file=sys.stderr)
        return 2
    lines = pem.decode().strip().splitlines()
    body = "\n".join(f'    "{ln}\\n"' for ln in lines)
    out = Path(a.out)
    out.write_text("// Generated by backend/tools/sign_firmware.py export-header. Release-signing PUBLIC key (not a secret). git-ignored: one per deployment.\n"
                   f"#pragma once\nstatic const char TORQVA_OTA_PUBKEY_PEM[] =\n{body};\n", encoding="utf-8")
    der = key.public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
    print(f"written: {out} (key fingerprint {hashlib.sha256(der).hexdigest()[:16]}); rebuild the firmware")
    return 0


def sign(a) -> int:
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    data = Path(a.bin).read_bytes()
    try:
        info = parse_esp_image(data)
        ident = firmware_identity(data)
    except FirmwareError as e:
        print(f"refusing: {e.code}: {e.detail}", file=sys.stderr)
        return 2
    if info["chip_id"] != 9:
        print(f"refusing: image is for chip id {info['chip_id']}, not the ESP32-S3", file=sys.stderr)
        return 2
    pem = Path(a.key).read_bytes()
    pw = None
    if b"ENCRYPTED" in pem:
        pw = (a.passphrase if a.passphrase is not None else getpass.getpass("passphrase: ")).encode()
    key = serialization.load_pem_private_key(pem, password=pw)
    msg = canonical(ident["ver"], len(data), hashlib.sha256(data).hexdigest())
    sig = base64.b64encode(key.sign(msg.encode(), ec.ECDSA(hashes.SHA256()))).decode()
    Path(str(a.bin) + ".sig").write_text(sig + "\n", encoding="ascii")
    print(f"version {ident['ver']}, {len(data)} bytes, signed: {msg}")
    print(sig)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    k = sub.add_parser("keygen"); k.add_argument("--out-dir", required=True); k.add_argument("--passphrase", default=None, help=argparse.SUPPRESS)
    h = sub.add_parser("export-header"); h.add_argument("--pub", required=True); h.add_argument("--out", default=str(REPO / "esp32" / "torqva_fw" / "src" / "ota_pubkey.h"))
    s = sub.add_parser("sign"); s.add_argument("--key", required=True); s.add_argument("--bin", required=True); s.add_argument("--passphrase", default=None, help=argparse.SUPPRESS)
    a = ap.parse_args()
    return {"keygen": keygen, "export-header": export_header, "sign": sign}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
